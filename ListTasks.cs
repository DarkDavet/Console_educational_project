        /*
        Задание 5: «Очистка данных от аномалий» 
       Цель: Столкнуться с классической ошибкой — изменением размера списка во время его перебора.
       Текст задания:Метеостанция прислала список температур за день: List<int> temperatures = new() { 22, -99, 25, 23, -99, 19 };
       Число -99 означает сбой датчика (аномалию). 
       Напиши программу, которая удаляет из списка все ошибочные значения -99. 
       Учти момент: Если ты попробуешь сделать это через обычный цикл foreach, программа выдаст ошибку (коллекция была изменена). 
       Тебе нужно использовать цикл for, причем идти по списку с конца в начало (от .Count - 1 до 0). 
       Попробуй разобраться, почему при удалении элементов с конца программа работает корректно, а с начала — пропускает элементы или падает.
       */
 static void task5()
    {
        List<int> temperatures = new() { 22, -99, 25, 23, -99, 19 };

        for (int i = temperatures.Count - 1; i >= 0; i--)
        {
            if (temperatures[i] == -99)
            {
                temperatures.RemoveAt(i); 
            }
        }

        Console.WriteLine(string.Join(", ", temperatures));
    }
