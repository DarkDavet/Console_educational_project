        /*
        Задача 3: «Модерация чата»
        Текст задания: В чат поддержки поступил список сообщений от пользователей. 
        Некоторые из них содержат спам или запрещенные слова, помеченные маркером "[SPAM]".
        Напиши программу, которая удаляет все спам-сообщения из списка:
        "Привет", "[SPAM]", "[SPAM]", "Нужна помощь", "Купи слона [SPAM]", "Спасибо"
        */

public void CleanChat()
   {
    List<string> chatMessages = new List<string>() { "Привет", "[SPAM]", "[SPAM]", "Нужна помощь", "Купи слона [SPAM]", "Спасибо" };
    for (int i = chatMessages.Count - 1; i >= 0; i--)
    {
        if (chatMessages[i].Contains("[SPAM]"))
        {
            chatMessages.RemoveAt(i);
        }
    }
    Console.WriteLine(string.Join(", ", chatMessages));
  }
