using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace Console_educational_project
{
    public class ListTasks
    {
        public void DemonstrateListWork()
        {
            Console.WriteLine("=== ДЕМОНСТРАЦИЯ РАБОТЫ С LIST ===\n");

            // 1. ИНИЦИАЛИЗАЦИЯ (Создание списка)
            // Создаем пустой список строк, где будут храниться названия задач
            List<string> taskList = new List<string>();


            // 2. МЕТОД ADD (Добавление элементов в конец списка)
            taskList.Add("Написать код");      // Станет на индекс 0
            taskList.Add("Протестировать программу"); // Станет на индекс 1
            taskList.Add("Выгрузить на сервер");   // Станет на индекс 2


            // Свойство .Count показывает текущее количество элементов в списке
            Console.WriteLine($"Шаг 1: Создан список. Всего задач: {taskList.Count}");
            // Выведет весь список в консоль через запятую для наглядности
            Console.WriteLine($"Текущий список: {string.Join(", ", taskList)}\n");


            // 3. МЕТОД INSERT (Вставка элемента в конкретное место по индексу)
            // Нам прилетела срочная задача. Вставляем её в самое начало — на индекс 0.
            // Все остальные задачи автоматически сдвинутся вправо (их индексы увеличатся на 1).
            taskList.Insert(0, "Исправить критический баг");

            Console.WriteLine("Шаг 2: Вставили срочную задачу в начало (на индекс 0).");
            // На индексе 1 теперь окажется "Написать код", которая раньше была первой
            Console.WriteLine($"Задача на индексе 1: {taskList[1]}");
            Console.WriteLine($"Текущий список: {string.Join(", ", taskList)}\n");


            // 4. МЕТОД CONTAINS (Проверка, есть ли элемент в списке)
            Console.WriteLine("Шаг 3: Проверяем наличие задачи 'Протестировать программу'...");

            // Метод Contains возвращает true (истина) или false (ложь)
            if (taskList.Contains("Протестировать программу"))
            {
                Console.WriteLine("-> Результат: Да, такая задача найдена в списке!");
            }
            else
            {
                Console.WriteLine("-> Результат: Нет, такой задачи в списке нет.");
            }
            Console.WriteLine();


            // 5. МЕТОД REMOVE (Удаление элемента по его имени/значению)
            Console.WriteLine("Шаг 4: Удаляем задачу 'Протестировать программу' (выполнили её).");

            // Метод ищет элемент с таким текстом и удаляет его. 
            // Элементы, стоявшие ЗА ним, автоматически сдвигаются влево (их индексы уменьшаются).
            taskList.Remove("Протестировать программу");

            Console.WriteLine($"Всего задач осталось: {taskList.Count}");
            Console.WriteLine($"Итоговый список: {string.Join(", ", taskList)}\n");

            Console.WriteLine("=================================");
        }
        /*
          Задание 1: «Система логирования» 
        Цель: Научиться создавать список, добавлять (Add), удалять (Remove) элементы и проверять их наличие (Contains).
        Текст задания:Ты пишешь модуль безопасности для сервера. 
        Сервер записывает события (логи) в список строк List<string> serverLogs.

        Добавь в список три записи: "Пользователь вошел", "Ошибка подключения к БД", "Файл скачан".
        Выведи в консоль общее количество записанных логов (используй свойство .Count).
        Представим, что ошибку подключения исправили, поэтому удали запись "Ошибка подключения к БД" из списка.
        Проверь с помощью .Contains(), осталась ли в списке запись "Пользователь вошел". 
        Если да, выведи в консоль: "Сессия активна".
         */

    }
}
